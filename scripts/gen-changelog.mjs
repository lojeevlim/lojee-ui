// Generates src/generated/changelog.ts from the git history, so the Changelog docs page always ships with the
// commits that exist at build time. (The page also fetches the latest commits live from GitHub in the browser.)
// Runs automatically before `npm run build`; run manually with `npm run docs:changelog`.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const SEP = "\u001f";
const END = "\u001e";

let raw = "";
try {
  raw = execFileSync("git", ["log", "--no-merges", "-n", "400", `--format=%H${SEP}%h${SEP}%aI${SEP}%an${SEP}%ae${SEP}%s${SEP}%b${END}`], { cwd: root, encoding: "utf8" });
} catch {
  console.warn("gen-changelog: git history unavailable — writing an empty changelog");
}

const commits = raw
  .split(END)
  .map((r) => r.trim())
  .filter(Boolean)
  .map((r) => {
    const [sha, short, date, author, email, subject, body = ""] = r.split(SEP);
    const lines = body
      .split("\n")
      .map((l) => l.trim())
      .filter((l) => l && !/^co-authored-by:/i.test(l) && !/^generated with/i.test(l));
    return { sha, short, date, author, email, subject: subject.trim(), body: lines.join("\n") };
  });

const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const out = `// AUTO-GENERATED by scripts/gen-changelog.mjs — do not edit. Run \`npm run docs:changelog\`.
export interface ChangelogCommit { sha: string; short: string; date: string; author: string; email: string; subject: string; body: string }

export const PACKAGE_VERSION = ${JSON.stringify(pkg.version)};
export const CHANGELOG_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};
export const CHANGELOG: ChangelogCommit[] = ${JSON.stringify(commits, null, 2)};
`;
fs.mkdirSync(path.join(root, "src/generated"), { recursive: true });
fs.writeFileSync(path.join(root, "src/generated/changelog.ts"), out);
console.log(`changelog: ${commits.length} commits`);
